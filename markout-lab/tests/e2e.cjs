'use strict';
const assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const {existsSync}=require('node:fs');
const path=require('node:path');
const {chromium}=require('playwright-core');
const root=path.join(__dirname,'..','..');
const url='http://127.0.0.1:8777';
const chrome=['/usr/bin/google-chrome','/usr/bin/google-chrome-stable','/usr/bin/chromium','/usr/bin/chromium-browser'].find(existsSync);
if(!chrome)throw new Error('No Chrome or Chromium binary available for E2E smoke test');
const server=spawn('python3',['-m','http.server','8777','--bind','127.0.0.1','--directory','markout-lab'],{cwd:root,stdio:'ignore'});
const sleep=ms=>new Promise(res=>setTimeout(res,ms));
async function ready(){for(let i=0;i<60;i++){try{const r=await fetch(url);if(r.ok)return;}catch(e){}await sleep(200);}throw Error('local server not reachable');}
(async()=>{
let browser;try{
 await ready();browser=await chromium.launch({executablePath:chrome,headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({acceptDownloads:true,viewport:{width:1450,height:1000}});
 const page=await context.newPage();const errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 const response=await page.goto(url,{waitUntil:'domcontentloaded'});assert.equal(response.status(),200);
 await page.waitForFunction(()=>{const k=document.querySelector('#kpi-best');return k&&k.textContent!=='—';},{},{timeout:20000});
 assert.equal(await page.locator('#comparison-rows tr').count(),3);
 assert.equal(await page.locator('#stress-heatmap .heat-cell').count(),25);
 assert.equal(await page.locator('#book-ladder .book-row').count(),13);
 assert.equal(await page.locator('#equity-chart svg').count(),1);
 assert.equal(await page.locator('#markout-chart svg').count(),1);
 const defaultRun=await page.locator('#run-info').innerText();
 assert.match(defaultRun,/SEED 4172/);
 assert.match(defaultRun,/720 EVENTS/);
 await page.locator('#methods-btn').click();
 assert.equal(await page.locator('#method-dialog').evaluate(el=>el.open),true);
 await page.locator('#close-methods').click();
 assert.equal(await page.locator('#method-dialog').evaluate(el=>el.open),false);
 await page.locator('[data-strategy="fixed"]').click();
 assert.match(await page.locator('#pnl-reconcile').innerText(),/RECONCILIATION/);
 await page.locator('#seed').fill('2341');
 await page.locator('#run').click();
 await page.waitForFunction(()=>document.querySelector('#run-info').textContent.includes('SEED 2341'),{},{timeout:20000});
 assert.equal(await page.locator('#comparison-rows tr').count(),3);
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#export').click()]);
 assert.match(download.suggestedFilename(),/markout-lab-seed-2341.json/);
 const csvWait=page.waitForEvent('download');await page.locator('#csv').click();assert.match((await csvWait).suggestedFilename(),/strategies.csv/);
 await page.screenshot({path:'/tmp/markout-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/markout-mobile.png',fullPage:true});
 const mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
 assert.ok(mobileOverflow<=3,'mobile horizontal overflow '+mobileOverflow);
 assert.equal(errors.length,0,'uncaught browser errors: '+errors.join('; '));
 console.log('MARKOUT LAB BROWSER PASS — desktop/mobile, charts, scenarios, modal, strategy selection and exports.');
}finally{if(browser)await browser.close();server.kill('SIGTERM');}
})().catch(e=>{console.error(e);process.exitCode=1;});
