const assert=require('node:assert/strict');
const {plan}=require('../dist/agent.js');
const {defaults,validate}=require('../dist/model.js');
const s=defaults();
assert.deepEqual(plan('Lower London rent by £200',s),{tool:'update_assumption',option:1,field:'rent',value:1450});
assert.deepEqual(plan('London rent is £1,450',s),{tool:'update_assumption',option:1,field:'rent',value:1450});
assert.deepEqual(plan('Increase Manchester salary by £100',s),{tool:'update_assumption',option:0,field:'income',value:3000});
assert.equal(plan('What would change my mind?',s).tool,'find_tipping_point');
assert.equal(plan('Show me the downside',s).tool,'inspect_downside');
assert.equal(plan('Value my time at £20 an hour',s).value,20);
assert.equal(plan('Undo',s).tool,'undo');
assert.equal(plan('Make up a winning probability',s).tool,'help');
const negative=plan('London rent is -100',s);
assert.equal(negative.value,-100);
const invalid=defaults();invalid.options[1].rent=negative.value;
assert.throws(()=>validate(invalid));
assert.equal(plan('Lower rent by 200 and raise salary by 400',s).tool,'help');
assert.equal(plan('Lower London rent by two hundred pounds',s).value,1450);
assert.equal(plan('London rent is one thousand four hundred and fifty pounds',s).value,1450);
assert.equal(plan('Value my time at twenty pounds an hour',s).value,20);
console.log('14 planner and validation assertions passed.');
